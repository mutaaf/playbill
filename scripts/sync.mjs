#!/usr/bin/env node
// Which pages Playbill fronts comes from Cast List (mutaafaziz.com/cast), the portfolio's one app catalog.
// This writes src/cast.js (path → app id, binding, identity facts) and the services + app routes in
// wrangler.jsonc. Cloudflare needs routes and bindings at deploy time, so they're generated, not looked up live.
//   node scripts/sync.mjs           regenerate
//   node scripts/sync.mjs --check   fail if anything is out of date (CI)
// CAST_FEED=<url or file> overrides the feed (tests, offline).
import { readFile, writeFile } from 'node:fs/promises';

const FEED = process.env.CAST_FEED || 'https://mutaafaziz.com/cast/api/apps';
const HOST = 'mutaafaziz.com';
// Routes Playbill owns for itself, whatever the catalog says.
const OWN = ['robots.txt', 'sitemap.xml', 'llms-full.txt', '{INDEXNOW_KEY}.txt', 'playbill', 'playbill/*'];
const root = new URL('..', import.meta.url);

async function feed() {
  const raw = /^https?:/.test(FEED) ? await (await fetch(FEED, { headers: { 'user-agent': 'playbill-sync' } })).text() : await readFile(FEED, 'utf8');
  const body = JSON.parse(raw);
  const apps = Array.isArray(body) ? body : body.apps;
  if (!Array.isArray(apps) || !apps.length) throw new Error(`no apps in ${FEED}`);
  return apps;
}

export function plan(apps, wrangler) {
  const fronted = apps
    .filter((a) => (a.surfaces || []).includes('playbill') && a.ids?.playbill && new URL(a.url).hostname === HOST)
    .map((a) => {
      if (!a.worker) throw new Error(`${a.slug} is on Playbill but Cast List has no worker for it`);
      const path = new URL(a.url).pathname.replace(/\/?$/, '/');
      const id = a.ids.playbill;
      return { path, id, slug: a.slug, binding: id === 'site' ? 'SITE' : id.toUpperCase().replace(/[^A-Z0-9]/g, '_'), worker: a.worker, name: a.name, url: a.url, audience: a.audience };
    })
    .sort((x, y) => (x.path === '/' ? -1 : y.path === '/' ? 1 : x.path.localeCompare(y.path)));
  // Apps on other hosts (18-0.co) are served through /playbill/ext/<id>/ and need no binding.
  const external = apps.filter((a) => (a.surfaces || []).includes('playbill') && a.ids?.playbill && new URL(a.url).hostname !== HOST)
    .map((a) => ({ id: a.ids.playbill, slug: a.slug, name: a.name, url: a.url, audience: a.audience }));

  const key = wrangler.vars?.INDEXNOW_KEY;
  const routes = [];
  for (const f of fronted) {
    routes.push(`${HOST}${f.path}`);
    if (f.path !== '/') routes.push(`${HOST}${f.path}llms.txt`);
  }
  for (const r of OWN) routes.push(`${HOST}/${r.replace('{INDEXNOW_KEY}', key)}`);
  const services = [...new Map(fronted.map((f) => [f.binding, { binding: f.binding, service: f.worker }])).values()];
  const next = { ...wrangler, services, routes: routes.map((pattern) => ({ pattern, zone_name: HOST })) };

  const castJs = `// Generated by scripts/sync.mjs from Cast List (mutaafaziz.com/cast/api/apps). Do not edit; run npm run sync.
// Identity (name, url, audience) is Cast List's; everything else about an app's search copy is Playbill's (D1).
export const FRONTED = ${JSON.stringify(Object.fromEntries(fronted.map((f) => [f.path, { id: f.id, binding: f.binding }])), null, 2)};
export const IDENTITY = ${JSON.stringify(Object.fromEntries([...fronted, ...external].map((a) => [a.id, { slug: a.slug, name: a.name, url: a.url, audience: a.audience }])), null, 2)};
`;
  return { next, castJs, ids: [...fronted, ...external].map((a) => a.id) };
}

// wrangler.jsonc keeps its leading comment block; the JSON body below it is regenerated.
function splitJsonc(text) {
  const i = text.indexOf('{');
  return { head: text.slice(0, i), json: JSON.parse(text.slice(i)) };
}

async function main() {
  const check = process.argv.includes('--check');
  const wPath = new URL('wrangler.jsonc', root), cPath = new URL('src/cast.js', root);
  const wText = await readFile(wPath, 'utf8');
  const { head, json } = splitJsonc(wText);
  const { next, castJs, ids } = plan(await feed(), json);
  const wNext = `${head}${JSON.stringify(next, null, 2)}\n`;
  const cOld = await readFile(cPath, 'utf8').catch(() => '');
  const catalog = JSON.parse(await readFile(new URL('catalog.json', root), 'utf8'));
  const noCopy = ids.filter((id) => !catalog.some((a) => a.id === id));
  const stale = [wNext !== wText && 'wrangler.jsonc', castJs !== cOld && 'src/cast.js'].filter(Boolean);
  if (check) {
    const problems = [];
    if (stale.length) problems.push(`${stale.join(' and ')} out of date with Cast List: run npm run sync`);
    if (noCopy.length) problems.push(`Cast List puts ${noCopy.join(', ')} on Playbill but catalog.json has no entry: write its search copy`);
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log(`in sync: ${ids.length} apps`);
    return;
  }
  if (stale.includes('wrangler.jsonc')) await writeFile(wPath, wNext);
  if (stale.includes('src/cast.js')) await writeFile(cPath, castJs);
  console.log(stale.length ? `wrote ${stale.join(', ')}` : 'already in sync');
  if (noCopy.length) console.log(`still needs search copy in catalog.json: ${noCopy.join(', ')}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e.message); process.exit(1); });
